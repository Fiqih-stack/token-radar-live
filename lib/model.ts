// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other pre-token protocol the snapshot carries that can be ranked: no pre-token protocol is left
// out because it sits below the floor. A protocol is pre-token when its index entry records no
// token (no market cap, no CoinGecko id, no symbol); the snapshot's live-token protocols are kept
// apart and shown with the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, and the market's own pricing of
// protocols that already trade:
//
//   category multiple = the median market-cap / TVL of the live-token protocols in the same
//                         category (at least 3 of them, else the global median), clamped to
//                         [0.05, 1.5]. A lending protocol is priced like lending protocols trade,
//                         a DEX like DEXes trade; no name is ever special-cased.
//   base               = tvl_usd x category multiple
//   growth             = clamp(change_7d, -60, 120) per cent
//   growthMult         = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity           = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth            = 1 + min(chains - 1, 4) x 0.03
//   implied            = max(1, round(base x growthMult x maturity x breadth))
//
// The constants are stated in the dashboard and changeable in the model sandbox. The same function
// scores every row, and the dashboard recomputes every row from the same figures.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
  multiple_floor: number;
  multiple_cap: number;
  multiple_min_samples: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  breadth_per_chain: 0.03,
  breadth_max_chains: 4,
  multiple_floor: 0.05,
  multiple_cap: 1.5,
  multiple_min_samples: 3,
};

